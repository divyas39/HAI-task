"""AI assistance: a Gemini LLM judges whether a review was written by a human or an AI.

`detect(text, stars)` is the function the A3 interface will call in real time.
Run as a script to label every trial in data/study.csv, or pass a review to try one:
    python run_model.py "This place was great..."
"""
import json
import os
import threading
import time
import sys
from concurrent.futures import ThreadPoolExecutor
from typing import Literal

import pandas as pd
from dotenv import load_dotenv
from google import genai
from google.genai import types
from pydantic import BaseModel

load_dotenv()
# Gemini, so the detector never judges text from its own model family (the AI reviews are Claude's).
DETECTOR = os.getenv("DETECTOR_MODEL", "gemini-3.5-flash-lite")
# reads GEMINI_API_KEY; retries 429s so free-tier rate limits just slow the run down
client = genai.Client(http_options=types.HttpOptions(retry_options=types.HttpRetryOptions(
    attempts=4, initial_delay=5, max_delay=30, http_status_codes=[429, 500, 503])))

# Iteration 2 (see README): the zero-shot prompt called almost everything "Human" (53% accuracy),
# so the prompt now states the base rate, lists cues, and shows labelled examples.
SYSTEM = """You help people decide whether an online review (restaurants, shops, services) was \
written by a human customer or generated by an AI language model. About half of the reviews you \
see are AI-generated. Modern AI reviews sound conversational and include specific-sounding details \
(dishes, wait times, staff names), so a natural tone or specifics alone are NOT evidence of a human.

Cues that point to AI: tidy structure (verdict, then details, then a balanced caveat such as "the \
only reason I'm not giving five stars", then a closing recommendation); flawless spelling, grammar \
and punctuation; stock phrases ("overall", "hidden gem", "went above and beyond", "do yourself a \
favor"); every complaint or compliment neatly resolved.
Cues that point to a human: typos, run-on sentences, odd capitalization or punctuation, slang, \
abrupt endings, tangents, references to other reviewers or very local specifics, uneven pacing.

Judge the text only. Give your best label, a confidence from 50 (pure guess) to 100 (certain), \
and a one- or two-sentence reason that points to concrete cues in the text a reader can check \
themselves.

Labelled examples (not part of the study set):
{examples}"""


def _examples():
    # Spare reviews from the pool that are not in the study set.
    pool, study = pd.read_csv("data/pool.csv"), pd.read_csv("data/study.csv")
    spare = pool[~pool.id.isin(study.id)]
    picked = pd.concat([spare[spare.ground_truth == g].head(2) for g in ("Human", "AI")])
    return "\n\n".join(f"[{r.ground_truth}] {r.text}" for r in picked.itertuples())


SYSTEM = SYSTEM.format(examples=_examples())


class Verdict(BaseModel):
    label: Literal["Human", "AI"]
    confidence: int
    reason: str


def detect(text, stars=None):
    rating = f"Star rating: {stars}/5\n" if stars else ""
    r = client.models.generate_content(
        model=DETECTOR, contents=f"{rating}Review:\n{text}",
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM, temperature=0,
            thinking_config=types.ThinkingConfig(thinking_level="LOW"),  # fast enough for a live interface
            response_mime_type="application/json", response_schema=Verdict),
    )
    v = r.parsed
    return {"model_output": v.label, "model_confidence": max(50, min(100, v.confidence)),
            "model_reason": v.reason}


CACHE = "data/model_outputs.jsonl"  # one line per labelled trial, so a stopped run can resume


def main():
    df = pd.read_csv("data/study.csv")
    done = pd.read_json(CACHE, lines=True) if os.path.exists(CACHE) else pd.DataFrame(columns=["id", "detector"])
    todo = df[~df.id.isin(done[done.detector == DETECTOR].id)]
    lock = threading.Lock()

    def label(row):
        out = {"id": row.id, "detector": DETECTOR, **detect(row.text, row.stars)}
        with lock, open(CACHE, "a") as f:
            f.write(json.dumps(out) + "\n")
        time.sleep(5)  # free tier allows 15 requests/min

    with ThreadPoolExecutor(1) as ex:
        list(ex.map(label, todo.itertuples()))  # list() re-raises the first failure

    out = pd.read_json(CACHE, lines=True)
    out = out[out.detector == DETECTOR].drop(columns="detector")  # never mix models
    df = df.drop(columns=[c for c in ("model_output", "model_confidence", "model_reason") if c in df])
    df.merge(out, on="id", how="left").to_csv("data/study.csv", index=False)
    print(f"labelled {len(out)}/{len(df)} trials with {DETECTOR}")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        print(detect(" ".join(sys.argv[1:])))
    else:
        main()
